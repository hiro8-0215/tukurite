import assert from 'node:assert/strict';
import {ingredientAmount,shoppingList,shoppingAmount,weekStart,shiftDate} from '../src/lib/planning.ts';
let checks=0;const check=(v,m)=>{assert.ok(v,m);checks++;};
check(ingredientAmount('しょうゆ 小さじ1').quantity===1,'Japanese spoon prefix');
check(ingredientAmount('玉ねぎ 1/2個').quantity===.5,'fraction');
check(ingredientAmount('玉ねぎ ½個').quantity===.5,'Unicode fraction');
check(ingredientAmount('豆腐 ０．１５kg').quantity===150,'fullwidth and kilograms');
check(ingredientAmount('1/2個 玉ねぎ').name==='玉ねぎ','leading quantity');
check(ingredientAmount('ブロッコリー 1/2株').quantity===.5&&ingredientAmount('鮭 2切れ').quantity===2,'common vegetable and fish units');
check(ingredientAmount('水 100cc').unit==='ml','cc can be combined with ml');
check(ingredientAmount('塩 少々').quantity===null,'vague amounts are not invented');
check(ingredientAmount('水 1〜2カップ').quantity===null,'ranges are not silently summed');
check(ingredientAmount('米 1,000g').quantity===null&&ingredientAmount('水 1と2カップ').quantity===null,'unsupported numeric notation is preserved for confirmation');
check(ingredientAmount('レモン果汁 大さじ1と1/2').quantity===1.5,'AI mixed fraction can be consolidated');
check(ingredientAmount('水 1½カップ').quantity===1.5&&ingredientAmount('水 1 1/2カップ').quantity===1.5,'mixed Unicode and spaced fractions remain one and a half');
const meals=[{id:'a',plan_day:'2026-11-03',slot:'夜',servings:4,snapshot:{title:'A',ingredients:'豆腐 150g\nしょうゆ 小さじ1\n塩 適量',servings:2}},{id:'b',plan_day:'2026-11-03',slot:'夜',servings:1,snapshot:{title:'B',ingredients:'豆腐 0.1kg\nしょうゆ 小さじ1\n水 200ml',servings:1}}];
const list=shoppingList(meals);
check(list.find(x=>x.name==='豆腐').quantity===400,'serving ratios and compatible units combine');
check(shoppingAmount(list.find(x=>x.name==='しょうゆ'))==='小さじ3','spoons combine without arbitrary conversions');
check(shoppingAmount(list.find(x=>x.name==='塩')).includes('2倍'),'unknown amounts retain adjustment context');
check(shoppingList([{...meals[0],snapshot:{...meals[0].snapshot,ingredients:'油 大さじ1\n油 10g'}}]).length===2,'incompatible units are kept separate');
check(weekStart('2026-11-03')==='2026-11-02'&&weekStart('2026-11-01')==='2026-10-26','Monday calendar and Sunday rollover');
check(shiftDate('2026-12-31',1)==='2027-01-01','year rollover');
console.log(`PASS ${checks} meal planning and shopping quantity checks`);
