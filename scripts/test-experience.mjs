import assert from 'node:assert/strict';
import {matchesSearch,findRecipes,recipeIssue,isHttpsUrl,readDraft,writeDraft,removeDraft} from '../src/lib/experience.ts';
let checks=0;
function check(value,message){assert.ok(value,message);checks++;}
const base={id:'one',owner:'haru',title:'豆腐のレモンあえ',description:'加熱しない',ingredients:'豆腐 150g\nレモン汁 小さじ1',steps:'混ぜる',minutes:5,servings:1,category:'副菜',image:'none',status:'published',version:1,hash:'',sample:0,created:'2026-10-20T10:00:00Z',updated:'2026-10-20T10:00:00Z',saves:8,authorName:'HARU'};
const recipes=[base,{...base,id:'two',owner:'yui',title:'トマトパスタ',category:'麺類',ingredients:'トマト、パスタ',created:'2026-10-22T10:00:00Z',saves:2}];
check(matchesSearch('豆腐　レモン',base.title,base.ingredients),'multiple ingredients use AND matching');
check(matchesSearch('ｈａｒｕ',base.authorName),'fullwidth latin query matches');
check(!matchesSearch('豆腐 トマト',base.ingredients),'all query terms required');
check(findRecipes(recipes,'','すべて','','new')[0].id==='two','newest recipe first regardless of input order');
check(findRecipes(recipes,'','すべて','','saved')[0].id==='one','saved count order');
check(findRecipes(recipes,'豆腐 レモン','副菜','haru','new').length===1,'combined ingredient category author search');
check(findRecipes(recipes,'トマト','副菜','','new').length===0,'empty category/search intersection');
check(recipes[0].id==='one','sorting does not mutate source');
check(!recipeIssue(base),'complete recipe is valid');
check(recipeIssue({...base,ingredients:'  '}).includes('材料'),'blank ingredient blocks publishing');
check(recipeIssue({...base,minutes:0}).includes('調理時間'),'zero time blocks publishing');
check(recipeIssue({...base,servings:1.5}).includes('人数'),'fractional servings block publishing');
check(isHttpsUrl(' https://example.com/recipe '),'trimmed source URL accepted');
check(!isHttpsUrl('javascript:alert(1)')&&!isHttpsUrl('https://user:password@example.com/'),'unsafe source URLs rejected');
const values=new Map();
const storage={getItem:key=>values.get(key)??null,setItem:(key,value)=>values.set(key,value),removeItem:key=>values.delete(key)};
const draft={title:'書きかけ',description:'レモンでさっぱり',ingredients:'',steps:'',minutes:5,servings:1,category:'副菜',image:'none'};
check(writeDraft(storage,'alice',draft),'incomplete recipe can be saved privately');
check(readDraft(storage,'alice').description===draft.description,'draft survives a new read');
check(readDraft(storage,'bob')===null,'different account cannot restore draft');
writeDraft(storage,'alice',{...draft,id:'published-one',title:'改訂下書き'});
check(readDraft(storage,'alice').title==='書きかけ'&&readDraft(storage,'alice','published-one').title==='改訂下書き','new draft and revision are isolated');
removeDraft(storage,'alice','published-one');
check(readDraft(storage,'alice','published-one')===null&&!!readDraft(storage,'alice'),'publishing one draft leaves another draft intact');
values.set('tsukurite-draft-v1:alice:new','{invalid');
check(readDraft(storage,'alice')===null,'corrupt local draft does not crash editor');
const blocked={setItem(){throw Error('quota exceeded');},getItem(){throw Error('blocked');},removeItem(){throw Error('blocked');}};
check(!writeDraft(blocked,'alice',draft)&&readDraft(blocked,'alice')===null&&!removeDraft(blocked,'alice'),'blocked storage is handled without claiming success');
console.log(`PASS ${checks} UI behavior checks`);
